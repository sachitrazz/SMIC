def table_negative(diag, ratio):
    L = ["% AUTO-GENERATED by tools/make_tables.py -- do not edit",
         "\\begin{table}[htb]", "\\centering",
         "\\caption{A negative result, reported in full. Constraining each "
         "memory to a disjoint timescale band (Section~\\ref{sec:negative}) "
         "does \\emph{not} improve accuracy: it is far worse than an ordinary "
         "free-gate memory, and the deficit widens as the two required "
         "timescales separate, which is the opposite of what a coverage argument "
         "predicts. The bands occupy their intended ranges (median $\\tau$ per "
         "band $1.7$, $4.8$, $13.4$, $38.0$), so this is not a coverage "
         "failure. The explanation is that per-unit gates already supply "
         "timescale diversity, and hard tiling buys that diversity by removing "
         "capacity.}",
         "\\label{tab:negative}", "\\footnotesize",
         "\\begin{tabular}{@{}lcccc@{}}", "\\toprule",
         "\\textbf{Memory} & $\\tau_l/\\tau_s{=}2$ & $4$ & $8$ & $14$\\\\",
         "\\midrule"]
    rows = {r["ratio"]: r for r in ratio["rows"]}
    ks = [2, 4, 8, 14]
    L.append("Free per-unit gates ($K{=}1$) & " + " & ".join(
        pct(rows[k]["spectral_K1"]["acc_mean"]) if k in rows else "--" for k in ks) + "\\\\")
    L.append("Tiled disjoint bands ($K{=}4$) & " + " & ".join(
        pct(rows[k]["spectral"]["acc_mean"]) if k in rows else "--" for k in ks) + "\\\\")
    L.append("\\midrule")
    L.append("Difference & " + " & ".join(
        ("$-$" + pct(rows[k]["spectral_K1"]["acc_mean"] - rows[k]["spectral"]["acc_mean"]))
        if k in rows else "--" for k in ks) + "\\\\")
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    return "\n".join(L) + "\n"


# ----------------------------------------------------------------------

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    ap.add_argument("--out", default=os.path.join("out", "tables"))
    a = ap.parse_args()

    pos = load(os.path.join(a.results, "collapse_final.json"))
    ratio = load(os.path.join(a.results, "ratio_synthetic.json"))
    diag = load(os.path.join(a.results, "diagnose.json"))
    os.makedirs(a.out, exist_ok=True)
    written = []
    if pos:
        open(os.path.join(a.out, "collapse.tex"), "w", encoding="utf-8").write(
            table_collapse(pos)); written.append("collapse.tex")
    if ratio:
        open(os.path.join(a.out, "negative.tex"), "w", encoding="utf-8").write(
            table_negative(diag, ratio)); written.append("negative.tex")
    print("tables written : %s" % ", ".join(written))


if __name__ == "__main__":
    main()
